#!/usr/bin/env python3
"""Generates the shared (iOS) WorkHours sources from the Android sources.

Usage:  python3 tools/port_workhours.py

Reads   upstream/WorkHours-Android/app/src/{main,test}
Writes  WorkHours-iOS/composeApp/src/commonMain/kotlin/com/tal/workhours/   (ported app code)
        WorkHours-iOS/composeApp/src/commonMain/kotlin/com/tal/workhours/generated/  (R + string tables)
        WorkHours-iOS/composeApp/src/commonMain/composeResources/drawable/  (icons)
        WorkHours-iOS/composeApp/src/jvmTest/kotlin/com/tal/workhours/      (ported unit tests)

The Android code is kept as-is wherever possible: JDK and Android APIs are
redirected to the look-alikes in the `compat` package by rewriting imports,
and the few places that need real changes are listed in PATCHES below. Every
patch must match exactly once, so an upstream change that breaks a patch
fails loudly instead of silently producing wrong code.
"""
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "upstream/WorkHours-Android/app/src"
MAIN = SRC / "main/java/com/tal/workhours"
TEST = SRC / "test/java/com/tal/workhours"
RES = SRC / "main/res"
OUT = ROOT / "WorkHours-iOS/composeApp/src"
OUT_MAIN = OUT / "commonMain/kotlin/com/tal/workhours"
OUT_GEN = OUT_MAIN / "generated"
OUT_TEST = OUT / "jvmTest/kotlin/com/tal/workhours"
OUT_DRAWABLE = OUT / "commonMain/composeResources/drawable"

HEADER = "// GENERATED by tools/port_workhours.py from upstream/WorkHours-Android - do not edit.\n"

# Android-only files with no iOS counterpart yet (home-screen widgets, Google
# Drive backup, home-server sync). Small hand-written stand-ins live in
# commonMain/kotlin/com/tal/workhours/ios/.
SKIPPED = {
    "ShiftWidgetProvider.kt", "CompactShiftWidgetProvider.kt", "WorkCalendarWidgetProvider.kt",
    "DriveBackup.kt", "HomeSync.kt", "HomeSyncActivity.kt",
    "Localization.kt",   # replaced by ios/Localization.kt (strings come from generated tables)
    "BackupScreen.kt",   # replaced by ios/BackupScreen.kt (no Google Drive section)
}
SKIPPED_TESTS = set()

# (regex, replacement) applied to every ported main file.
REWRITES = [
    (r"\bjava\.time\.", "compat.time."),
    (r"\bjava\.math\.", "compat.math."),
    (r"\borg\.json\.", "compat.json."),
    (r"\bjava\.util\.zip\.", "compat.zip."),
    (r"\bjava\.io\.", "compat.io."),
    (r"\bjava\.text\.", "compat.text."),
    (r"\bjava\.security\.MessageDigest\b", "compat.security.MessageDigest"),
    (r"\bjava\.util\.(UUID|Locale|Currency)\b", r"compat.util.\1"),
    (r"(?<![\w.])android\.content\.Context\b", "compat.android.Context"),
    (r"(?<![\w.])android\.util\.AtomicFile\b", "compat.android.AtomicFile"),
    (r"(?<![\w.])android\.util\.Log\b", "compat.android.Log"),
    (r"\bandroidx\.annotation\.(StringRes|DrawableRes)\b", r"compat.android.\1"),
    (r"\bandroidx\.compose\.ui\.platform\.LocalContext\b", "compat.android.compose.LocalContext"),
    (r"\bandroidx\.compose\.ui\.res\.painterResource\b", "compat.android.compose.painterResource"),
    (r"\bandroidx\.activity\.compose\.BackHandler\b", "compat.android.compose.BackHandler"),
    (r"\bandroidx\.activity\.compose\.rememberLauncherForActivityResult\b", "compat.android.compose.rememberLauncherForActivityResult"),
    (r"\bandroidx\.activity\.result\.contract\.ActivityResultContracts\b", "compat.android.compose.ActivityResultContracts"),
    (r"(?<![\w.])android\.app\.(DatePickerDialog|TimePickerDialog)\b", r"compat.android.compose.\1"),
    (r"(?<![\w.])android\.widget\.Toast\b", "compat.android.compose.Toast"),
]
# Tests keep the real JDK for I/O so they cross-check our ZIP writer etc.
TEST_REWRITES = [
    (r"\bjava\.time\.", "compat.time."),
    (r"\bjava\.math\.", "compat.math."),
    (r"\borg\.json\.", "compat.json."),
    (r"\bjava\.util\.(UUID|Locale|Currency)\b", r"compat.util.\1"),
]
EXTRA_IMPORTS = "import compat.text.*\nimport compat.util.*\nimport kotlin.concurrent.Volatile\n"

# file -> list of patches, see tools/port_workhours_patches.py.
PATCHES = {}
TEST_PATCHES = {}


def load_patches():
    """Patches live next to this script so the long ones stay readable."""
    path = Path(__file__).with_name("port_workhours_patches.py")
    scope = {}
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), scope)
    PATCHES.update(scope.get("PATCHES", {}))
    TEST_PATCHES.update(scope.get("TEST_PATCHES", {}))
    SKIPPED_TESTS.update(scope.get("SKIPPED_TESTS", set()))


def port_source(text, name, rewrites, patches):
    for patch in patches.get(name, []):
        if len(patch) == 3:          # ("re", pattern, replacement)
            _, pattern, new = patch
            text, count = re.subn(pattern, lambda _m: new, text, flags=re.S | re.M)
            old = pattern
        else:                        # (exact old text, replacement)
            old, new = patch
            count = text.count(old)
            text = text.replace(old, new)
        if count != 1:
            sys.exit(f"{name}: patch expected exactly one match, found {count}:\n---\n{old}\n---")
    for pattern, replacement in rewrites:
        text = re.sub(pattern, replacement, text)
    # Insert the compat star imports right after the package line.
    match = re.search(r"^package [\w.]+\s*$", text, re.M)
    if not match:
        sys.exit(f"{name}: no package line")
    return HEADER + text[:match.end()] + "\n\n" + EXTRA_IMPORTS + text[match.end():]


# ---------------------------------------------------------------- strings ---

LANGUAGE_DIRS = {
    "values": "en", "values-iw": "he", "values-ar": "ar", "values-de": "de", "values-es": "es",
    "values-fr": "fr", "values-hi": "hi", "values-pt": "pt", "values-ru": "ru", "values-b+zh+Hans": "zh-Hans",
}


def android_unescape(raw):
    """Applies Android's string-resource rules: quotes, backslash escapes, whitespace."""
    out = []
    quoted = False
    i = 0
    pending_space = False
    while i < len(raw):
        c = raw[i]
        if c == "\\" and i + 1 < len(raw):
            n = raw[i + 1]
            if pending_space and out:
                out.append(" ")
            pending_space = False
            if n == "n":
                out.append("\n")
            elif n == "t":
                out.append("\t")
            elif n == "u" and i + 5 < len(raw) + 0:
                out.append(chr(int(raw[i + 2:i + 6], 16)))
                i += 4
            else:
                out.append(n)
            i += 2
            continue
        if c == '"':
            quoted = not quoted
            i += 1
            continue
        if not quoted and c.isspace():
            pending_space = True
            i += 1
            continue
        if pending_space and out:
            out.append(" ")
        pending_space = False
        out.append(c)
        i += 1
    return "".join(out)


def kotlin_literal(value):
    out = ['"']
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "$":
            out.append("\\$")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ch in "  ‎‏‪‫‬‭‮⁦⁧⁨⁩﻿":
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def read_strings(path):
    result = {}
    for node in ET.parse(path).getroot():
        if node.tag != "string":
            sys.exit(f"{path}: unsupported resource <{node.tag}>")
        raw = (node.text or "") + "".join(ET.tostring(child, encoding="unicode") for child in node)
        result[node.attrib["name"]] = android_unescape(raw)
    return result


def generate_strings():
    tables = {tag: read_strings(RES / folder / "strings.xml") for folder, tag in LANGUAGE_DIRS.items()}
    names = sorted(tables["en"])
    for tag, table in tables.items():
        unknown = set(table) - set(names)
        if unknown:
            sys.exit(f"{tag}: strings missing from the default language: {sorted(unknown)[:5]}")
    drawables = sorted(p.stem for p in OUT_DRAWABLE.iterdir())
    r = [HEADER, "package com.tal.workhours\n\n", "/** Resource ids, mirroring Android's generated R class. */\n", "object R {\n", "    object string {\n"]
    r += [f"        const val {name}: Int = {index}\n" for index, name in enumerate(names)]
    r += ["    }\n", "    object drawable {\n"]
    r += [f"        const val {name}: Int = {index}\n" for index, name in enumerate(drawables)]
    r += ["    }\n", "}\n"]
    (OUT_GEN / "R.kt").write_text("".join(r), encoding="utf-8")

    index = [HEADER, "package com.tal.workhours.generated\n\n",
             "/** Language tag -> strings indexed by R.string id. A null entry falls back to English. */\n",
             "internal val STRING_TABLES: Map<String, Array<String?>> = mapOf(\n"]
    for tag, table in tables.items():
        ident = "STRINGS_" + tag.replace("-", "_").upper()
        lines = [HEADER, "package com.tal.workhours.generated\n\n", f"internal val {ident}: Array<String?> = arrayOf(\n"]
        for name in names:
            lines.append("    " + (kotlin_literal(table[name]) if name in table else "null") + ",\n")
        lines.append(")\n")
        (OUT_GEN / f"Strings_{tag.replace('-', '_')}.kt").write_text("".join(lines), encoding="utf-8")
        index.append(f'    "{tag}" to {ident},\n')
    index.append(")\n")
    (OUT_GEN / "Strings.kt").write_text("".join(index), encoding="utf-8")

    res = [HEADER, "package com.tal.workhours.generated\n\n", "import com.tal.workhours.R\n",
           "import com.tal.workhours.res.*\n", "import org.jetbrains.compose.resources.DrawableResource\n\n",
           "/** Maps an R.drawable id to the bundled Compose resource. */\n",
           "internal fun drawableResource(id: Int): DrawableResource = when (id) {\n"]
    res += [f"    R.drawable.{name} -> Res.drawable.{name}\n" for name in drawables]
    res += ['    else -> error("Unknown drawable id $id")\n', "}\n"]
    (OUT_GEN / "Drawables.kt").write_text("".join(res), encoding="utf-8")
    return len(names), len(tables)


def copy_drawables(used):
    if OUT_DRAWABLE.exists():
        shutil.rmtree(OUT_DRAWABLE)
    OUT_DRAWABLE.mkdir(parents=True)
    for folder in ("drawable", "drawable-nodpi"):
        for path in sorted((RES / folder).iterdir()):
            if path.stem not in used:
                continue
            if path.suffix == ".xml" and "<vector" not in path.read_text(encoding="utf-8"):
                sys.exit(f"{path.name}: only vector drawables can be ported")
            shutil.copy(path, OUT_DRAWABLE / path.name)
    missing = used - {p.stem for p in OUT_DRAWABLE.iterdir()}
    if missing:
        sys.exit(f"drawables referenced but not found: {sorted(missing)}")


def main():
    load_patches()
    for folder in (OUT_GEN, OUT_TEST):
        if folder.exists():
            shutil.rmtree(folder)
        folder.mkdir(parents=True)
    for path in OUT_MAIN.glob("*.kt"):
        path.unlink()

    sources = sorted(p for p in MAIN.glob("*.kt") if p.name not in SKIPPED)
    sources += sorted((MAIN / "ui/theme").glob("*.kt"))
    used_drawables = set()
    for path in sources:
        if path.parent.name == "theme" and path.name == "Theme.kt":
            continue   # Android template leftover; the real theme is in AppDesign.kt
        text = port_source(path.read_text(encoding="utf-8"), path.name, REWRITES, PATCHES)
        used_drawables.update(re.findall(r"\bR\.drawable\.(\w+)", text))
        target = OUT_MAIN / ("ui/theme" if path.parent.name == "theme" else "") / path.name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    unused = set(PATCHES) - {p.name for p in sources}
    if unused:
        sys.exit(f"patches for unknown files: {sorted(unused)}")

    copy_drawables(used_drawables)
    strings, languages = generate_strings()

    tests = sorted(p for p in TEST.glob("*.kt") if p.name not in SKIPPED_TESTS)
    for path in tests:
        text = port_source(path.read_text(encoding="utf-8"), path.name, TEST_REWRITES, TEST_PATCHES)
        (OUT_TEST / path.name).write_text(text, encoding="utf-8")

    print(f"ported {len(sources)} sources, {len(tests)} tests, {strings} strings x {languages} languages, {len(used_drawables)} drawables")


if __name__ == "__main__":
    main()
